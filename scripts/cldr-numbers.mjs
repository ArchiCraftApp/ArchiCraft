// Generates crates/archicraft-app/src/i18n/cldr_numbers.rs: the decimal and
// grouping symbols (Latin digits) of about 100 locales, from the CLDR data in
// Node.js's ICU (STR-010). Run it with
//   node scripts/cldr-numbers.mjs > crates/archicraft-app/src/i18n/cldr_numbers.rs
// and record the CLDR version it prints in the file header.

const TAGS = `
af ar az be bg bn bs ca cs cy da de de-AT de-BE de-CH de-LI de-LU el
en en-AT en-AU en-BE en-CA en-CH en-DE en-DK en-FI en-GB en-IE en-IN en-NL en-NZ en-SE en-SI en-US en-ZA
es es-419 es-AR es-CL es-CO es-EC es-MX es-PE es-US es-UY es-VE et eu fa fi fil
fr fr-BE fr-CA fr-CH fr-LU ga gl gu he hi hr hu hy id is it it-CH ja ka kk km ko ky
lb lo lt lv mk ml mn mr ms mt my nb ne nl nl-BE nn no pa pl pt pt-PT rm ro ru
si sk sl sq sr sv sw ta te th tr uk ur uz vi zh zh-HK zh-TW zu
`.trim().split(/\s+/);

function symbols(tag) {
  const parts = new Intl.NumberFormat(tag, { numberingSystem: "latn", useGrouping: "always" })
    .formatToParts(1234567.5);
  const pick = (type) => parts.find((p) => p.type === type).value;
  return [pick("decimal"), pick("group")];
}

function rustChar(c) {
  const code = c.codePointAt(0);
  if (c.length !== 1) throw new Error(`not one UTF-16 unit: ${JSON.stringify(c)}`);
  if (code >= 0x20 && code < 0x7f && c !== "'" && c !== "\\") return `'${c}'`;
  return `'\\u{${code.toString(16).toUpperCase()}}'`;
}

const rows = TAGS.slice().sort().map((tag) => {
  const [decimal, group] = symbols(tag);
  return `    ("${tag}", ${rustChar(decimal)}, ${rustChar(group)}),`;
});

console.log(`//! Decimal and grouping symbols of common locales (STR-010), for
//! platforms without a number-locale API (Linux) and as the fallback when the
//! operating system's answer is unusable.
//!
//! Generated by \`scripts/cldr-numbers.mjs\` from CLDR ${process.versions.cldr}
//! (ICU ${process.versions.icu}, Node.js ${process.version}), Latin digits; the
//! data is under the Unicode License v3 (Unicode-3.0). Do not edit by hand.
//!
//! Indian locales group the digits above the thousands in pairs
//! (12,34,567.5); NumberFormat groups in threes only, so they get three-digit
//! groups with the same characters.

/// CLDR version of [\`NUMBER_SYMBOLS\`].
pub const CLDR_VERSION: &str = "${process.versions.cldr}";

/// \`(BCP 47 tag, decimal separator, grouping separator)\`, sorted by tag.
pub const NUMBER_SYMBOLS: &[(&str, char, char)] = &[
${rows.join("\n")}
];`);
