#!/usr/bin/env python3
"""Implementation status of the SRS requirements: generate, check and merge-check.

docs/status/requirements.json is the source of truth: one row per live requirement of
docs/SRS.md with its status (done, partial, missing), remaining effort, evidence (done rows)
or gap (the others) and dependencies. Priorities, sections and the row order come from the
SRS. This script writes the derived tables of docs/implementation-status.md between
`<!-- status:begin NAME -->` and `<!-- status:end NAME -->` markers and checks them per merge
(docs/testing.md, "Implementation status").

    python3 scripts/status.py generate
    python3 scripts/status.py check
    python3 scripts/status.py merge-check --base <sha> [--body-file <file>]

check fails on a live SRS ID without a row, a row for a withdrawn or unknown ID, a row whose
priority or section disagrees with the SRS, an evidence path to a missing file, a done row
without a test or CI guard reference (in its evidence or in the docs/testing.md traceability
table) and any difference between the document and what generate writes.

merge-check reads the `SRS:` lines of the pull-request body (--body-file, else the event
payload at $GITHUB_EVENT_PATH) and of the commit messages base..HEAD. Every listed ID's row
must differ between base and HEAD, and no row may move from done to partial or missing unless
a `Regresses: <ID> <reason>` line names it.

Python 3 standard library only. Tests: python3 scripts/tests/test_status.py
"""

import argparse
import json
import os
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JSON_PATH = "docs/status/requirements.json"
DOC_PATH = "docs/implementation-status.md"
SRS_PATH = "docs/SRS.md"
TESTING_PATH = "docs/testing.md"

STATUSES = ("done", "partial", "missing")
PRIORITIES = ("M", "S", "C")
EFFORTS = ("S", "M", "L", "XL")
FIELDS = ("id", "priority", "section", "status", "remaining_effort", "evidence", "gap", "depends_on")

ID_RE = r"[A-Z][A-Z0-9]{0,4}(?:-[A-Z][A-Z0-9]{0,4})?-[0-9]{2,3}"
SRS_REQ = re.compile(r"^- \*\*(" + ID_RE + r")\*\* · (?:([MSC]) |\*withdrawn)")
SRS_SECTION = re.compile(r"^#{3,4} ([0-9]+(?:\.[0-9]+)+) (.+?)\s*$")
SRS_TOP = re.compile(r"^## ")
MARKERS = ("counts", "sections", "requirements")
GENERATED_NOTE = "<!-- Generated by scripts/status.py from docs/status/requirements.json; do not edit. -->"
# Repository-relative paths in evidence text: a tracked top-level directory, then path segments.
PATH_TOKEN = re.compile(r"(?<![\w./-])((?:crates|docs|scripts|conformance|fuzz|\.github)/[\w./*-]*)")
IDENT = re.compile(r"\b[a-z][a-z0-9]*(?:_[a-z0-9]+)+\b")


class StatusError(Exception):
    pass


# --- sources -----------------------------------------------------------------------------


def parse_srs(text):
    """Live requirements in document order and the withdrawn IDs.

    Returns ({id: (priority, section)}, [section (number, title) in order], withdrawn ids).
    """
    live = {}
    sections = []
    withdrawn = set()
    current = None
    for line in text.splitlines():
        m = SRS_SECTION.match(line)
        if m:
            current = (m.group(1), m.group(2))
            continue
        if SRS_TOP.match(line):
            current = None
            continue
        m = SRS_REQ.match(line)
        if not m:
            continue
        rid, pri = m.group(1), m.group(2)
        if pri is None:
            withdrawn.add(rid)
            continue
        if current is None:
            raise StatusError(f"{SRS_PATH}: {rid} is outside a numbered section")
        if rid in live:
            raise StatusError(f"{SRS_PATH}: {rid} appears twice")
        if not sections or sections[-1] != current:
            sections.append(current)
        live[rid] = (pri, current[0])
    return live, sections, withdrawn


def load_rows(text, source=JSON_PATH):
    try:
        data = json.loads(text)
    except json.JSONDecodeError as e:
        raise StatusError(f"{source}: not valid JSON: {e}")
    if not isinstance(data, dict) or not isinstance(data.get("requirements"), list):
        raise StatusError(f'{source}: expected an object with a "requirements" list')
    return data["requirements"]


def dump_rows(rows):
    return json.dumps({"requirements": rows}, ensure_ascii=False, indent=2) + "\n"


def row_text(row):
    return row["evidence"] if row["status"] == "done" else row["gap"]


# --- generate ----------------------------------------------------------------------------


def cell(text):
    return text.replace("|", "\\|")


def ordered_rows(rows, live):
    order = {rid: i for i, rid in enumerate(live)}
    return sorted((r for r in rows if r["id"] in order), key=lambda r: order[r["id"]])


def render_counts(rows):
    table = Counter((r["status"], r["priority"]) for r in rows)
    out = ["| Status | Must (M) | Should (S) | Could (C) | Total |", "|---|---:|---:|---:|---:|"]
    for status in STATUSES:
        counts = [table[(status, p)] for p in PRIORITIES]
        out.append(f"| {status} | " + " | ".join(map(str, counts)) + f" | {sum(counts)} |")
    totals = [sum(table[(s, p)] for s in STATUSES) for p in PRIORITIES]
    out.append("| **total** | " + " | ".join(map(str, totals)) + f" | {sum(totals)} |")
    open_rows = [r for r in rows if r["status"] != "done"]
    efforts = Counter(r["remaining_effort"] for r in open_rows)
    out.append("")
    out.append(
        f"Remaining effort of the {len(open_rows)} open requirements: "
        + ", ".join(f"{e} {efforts[e]}" for e in EFFORTS)
        + "."
    )
    return out


def render_sections(rows, sections):
    out = ["| Section | Title | Must | Should | Could | Total |", "|---|---|---|---|---|---:|"]
    for number, title in sections:
        mine = [r for r in rows if r["section"] == number]
        table = Counter((r["status"], r["priority"]) for r in mine)
        cells = ["/".join(str(table[(s, p)]) for s in STATUSES) for p in PRIORITIES]
        out.append(f"| {number} | {title} | " + " | ".join(cells) + f" | {len(mine)} |")
    return out


def render_requirements(rows, sections):
    out = []
    for number, title in sections:
        if out:
            out.append("")
        out += [f"### {number} {title}", "", "| ID | Pri | Status | Effort | Gap / evidence |", "|---|---|---|---|---|"]
        for r in rows:
            if r["section"] == number:
                out.append(
                    f"| {r['id']} | {r['priority']} | {r['status']} | {r['remaining_effort']} | {cell(row_text(r))} |"
                )
    return out


def render(rows, srs_text):
    bad = [
        str(r.get("id")) if isinstance(r, dict) else repr(r)
        for r in rows
        if not isinstance(r, dict) or set(r) != set(FIELDS)
    ]
    if bad:
        raise StatusError(f"{JSON_PATH}: rows without exactly the fields {', '.join(FIELDS)}: {', '.join(bad)}")
    live, sections, _ = parse_srs(srs_text)
    rows = ordered_rows(rows, live)
    return {
        "counts": render_counts(rows),
        "sections": render_sections(rows, sections),
        "requirements": render_requirements(rows, sections),
    }


def splice(doc, blocks):
    """The document with every marker block replaced by its generated lines."""
    for name in MARKERS:
        begin, end = f"<!-- status:begin {name} -->", f"<!-- status:end {name} -->"
        pattern = re.compile(re.escape(begin) + r"\n.*?" + re.escape(end), re.S)
        if len(pattern.findall(doc)) != 1:
            raise StatusError(f"{DOC_PATH}: expected exactly one {begin} … {end} block")
        body = "\n".join([begin, GENERATED_NOTE, "", *blocks[name], "", end])
        doc = pattern.sub(lambda _: body, doc)
    return doc


# --- check -------------------------------------------------------------------------------


def test_names(root):
    """Names of the Rust test functions and Python test methods in the repository."""
    names = set()
    test_attr = re.compile(r"\s*#\[(?:\w+::)?test\b")
    fn = re.compile(r"\s*(?:pub(?:\([^)]*\))?\s+)?(?:async\s+)?fn\s+([a-z_][a-z0-9_]*)")
    for path in (root / "crates").rglob("*.rs"):
        in_tests_dir = "tests" in path.relative_to(root).parts
        marked = False
        for line in path.read_text(encoding="utf-8").splitlines():
            m = fn.match(line)
            if m and (marked or in_tests_dir):
                names.add(m.group(1))
            if test_attr.match(line):
                marked = True
            elif not re.match(r"\s*(#\[|//|$)", line):
                marked = False
    for path in (root / "scripts").rglob("test_*.py"):
        names.update(re.findall(r"^\s*def (test_\w+)", path.read_text(encoding="utf-8"), re.M))
    return names


def ci_names(root):
    """Job names (`    name:` under a job) and step names (`- name:`) of the GitHub workflows."""
    names = set()
    for path in (root / ".github" / "workflows").glob("*.yml"):
        for m in re.finditer(r"^(?:    |\s*- )name:\s*(.+?)\s*$", path.read_text(encoding="utf-8"), re.M):
            names.add(m.group(1).strip("\"'"))
    return {n for n in names if len(n) >= 10 and "${{" not in n}


def traceability(testing_text):
    """{id: [regression-check text]} from the docs/testing.md traceability table."""
    rows = {}
    in_section = False
    for line in testing_text.splitlines():
        if line.startswith("## "):
            in_section = line.strip() == "## Done-requirement traceability"
            continue
        if not in_section or not line.startswith("| "):
            continue
        cells = [c.strip() for c in re.split(r"(?<!\\)\|", line)[1:-1]]
        if len(cells) >= 3 and re.fullmatch(ID_RE, cells[0]):
            rows.setdefault(cells[0], []).append(cells[2])
    return rows


def evidence_paths(text):
    """Repository paths named in evidence text, without line numbers or truncated tails."""
    paths = []
    for m in PATH_TOKEN.finditer(text):
        if text[m.end() : m.end() + 1] == "…":
            continue
        path = m.group(1).split(":")[0].rstrip(".,;/")
        path = path.split("*")[0].rstrip("/")
        if path:
            paths.append(path)
    return paths


def names_a_check(text, tests, cis, root):
    if any(name in tests for name in IDENT.findall(text)):
        return True
    for path in evidence_paths(text):
        parts = Path(path).parts
        if (root / path).is_file() and ("tests" in parts or parts[0] in ("scripts", "conformance")):
            return True
    return any(name in text for name in cis)


def check_rows(rows, srs_text, root, testing_text):
    """Every problem of the rows, as messages."""
    live, _, withdrawn = parse_srs(srs_text)
    problems = []
    rows = [r for r in rows if isinstance(r, dict)]
    seen = Counter(r.get("id") for r in rows)
    for rid, n in seen.items():
        if n > 1:
            problems.append(f"{rid}: {n} rows")
    for rid in live:
        if rid not in seen:
            problems.append(f"{rid}: live SRS requirement without a row")
    trace = traceability(testing_text)
    tests = cis = None
    for r in rows:
        rid = r.get("id")
        if set(r) != set(FIELDS):
            problems.append(f"{rid}: fields must be exactly {', '.join(FIELDS)}")
            continue
        if rid in withdrawn:
            problems.append(f"{rid}: row for a withdrawn requirement")
            continue
        if rid not in live:
            problems.append(f"{rid}: row for an ID that is not in {SRS_PATH}")
            continue
        pri, section = live[rid]
        if r["priority"] != pri:
            problems.append(f"{rid}: priority {r['priority']}, the SRS says {pri}")
        if r["section"] != section:
            problems.append(f"{rid}: section {r['section']}, the SRS says {section}")
        if r["status"] not in STATUSES:
            problems.append(f"{rid}: status {r['status']!r} is not one of {', '.join(STATUSES)}")
            continue
        want_effort = ("none",) if r["status"] == "done" else EFFORTS
        if r["remaining_effort"] not in want_effort:
            problems.append(f"{rid}: remaining_effort {r['remaining_effort']!r} for a {r['status']} row")
        if not isinstance(r["depends_on"], list) or any(d not in live for d in r["depends_on"]):
            problems.append(f"{rid}: depends_on must list live SRS IDs")
        if r["status"] == "done":
            if not r["evidence"].strip() or r["gap"]:
                problems.append(f"{rid}: a done row has evidence and no gap")
        elif not r["gap"].strip() or r["evidence"]:
            problems.append(f"{rid}: a {r['status']} row has a gap and no evidence")
        for path in evidence_paths(r["evidence"]):
            if not (root / path).exists():
                problems.append(f"{rid}: evidence path {path} does not exist")
        if r["status"] == "done":
            if tests is None:
                tests, cis = test_names(root), ci_names(root)
            texts = [r["evidence"], *trace.get(rid, [])]
            if not any(names_a_check(t, tests, cis, root) for t in texts):
                problems.append(
                    f"{rid}: done row names no test or CI guard (in its evidence or in the {TESTING_PATH} traceability table)"
                )
    return problems


# --- merge-check -------------------------------------------------------------------------


def strip_comments(text):
    return re.sub(r"<!--.*?-->", "", text, flags=re.S)


def listed_ids(texts):
    """IDs on `SRS:` lines and {id: reason} of `Regresses:` lines."""
    ids, regresses = [], {}
    for text in texts:
        for line in strip_comments(text).splitlines():
            m = re.match(r"\s*SRS:(.*)", line)
            if m:
                ids += [i for i in re.findall(ID_RE, m.group(1)) if i not in ids]
            m = re.match(r"\s*Regresses:\s*(" + ID_RE + r")\b\s*(.*)", line)
            if m:
                regresses[m.group(1)] = m.group(2).strip()
    return ids, regresses


def merge_problems(base_rows, head_rows, texts, base_has_json=True):
    """Problems of a pull request. Without a JSON at the base (the pull request that introduces
    it), base_rows come from the base's Markdown table: every listed row counts as changed, and
    only the regression check compares with them."""
    base = {r["id"]: r for r in base_rows}
    head = {r["id"]: r for r in head_rows}
    ids, regresses = listed_ids(texts)
    problems = []
    for rid in ids:
        if rid not in head:
            problems.append(f"{rid}: listed on an SRS line but has no row")
        elif base_has_json and base.get(rid) == head[rid]:
            problems.append(f"{rid}: listed on an SRS line but its row did not change")
    for rid, before in base.items():
        after = head.get(rid)
        if before["status"] == "done" and after is not None and after["status"] != "done":
            if not regresses.get(rid):
                problems.append(
                    f"{rid}: regresses from done to {after['status']} without a 'Regresses: {rid} <reason>' line"
                )
    return problems


def git(root, *args):
    return subprocess.run(["git", *args], cwd=root, check=True, capture_output=True, text=True).stdout


def markdown_rows(doc):
    """Status rows of a requirement table in Markdown (a base from before the JSON existed)."""
    rows = []
    for line in doc.splitlines():
        cells = [c.strip() for c in re.split(r"(?<!\\)\|", line)[1:-1]]
        if len(cells) == 5 and re.fullmatch(ID_RE, cells[0]) and cells[2] in STATUSES:
            rows.append({"id": cells[0], "status": cells[2]})
    return rows


def base_rows(root, base):
    """The rows at the base and whether they come from its JSON."""
    try:
        text = git(root, "show", f"{base}:{JSON_PATH}")
    except subprocess.CalledProcessError:
        try:
            return markdown_rows(git(root, "show", f"{base}:{DOC_PATH}")), False
        except subprocess.CalledProcessError:
            return [], False
    return load_rows(text, f"{base}:{JSON_PATH}"), True


def pr_body(body_file):
    if body_file:
        return Path(body_file).read_text(encoding="utf-8")
    event = os.environ.get("GITHUB_EVENT_PATH")
    if event and Path(event).is_file():
        payload = json.loads(Path(event).read_text(encoding="utf-8"))
        return (payload.get("pull_request") or {}).get("body") or ""
    return ""


# --- commands ----------------------------------------------------------------------------


def read(root, path):
    return (root / path).read_text(encoding="utf-8")


def cmd_generate(root):
    rows = load_rows(read(root, JSON_PATH))
    doc = splice(read(root, DOC_PATH), render(rows, read(root, SRS_PATH)))
    (root / DOC_PATH).write_text(doc, encoding="utf-8")
    return 0


def cmd_check(root):
    srs = read(root, SRS_PATH)
    rows = load_rows(read(root, JSON_PATH))
    problems = check_rows(rows, srs, root, read(root, TESTING_PATH))
    doc = read(root, DOC_PATH)
    try:
        in_sync = splice(doc, render(rows, srs)) == doc
    except StatusError as e:
        problems.append(str(e))
        in_sync = True
    if not in_sync:
        problems.append(
            f"{DOC_PATH}: the generated tables differ from {JSON_PATH}; edit the JSON and run python3 scripts/status.py generate"
        )
    for p in problems:
        print(f"status check: {p}", file=sys.stderr)
    if not problems:
        print(f"status check: {len(rows)} rows in sync")
    return 1 if problems else 0


def cmd_merge_check(root, base, body_file):
    head = load_rows(read(root, JSON_PATH))
    commits = git(root, "log", "--format=%B%x00", f"{base}..HEAD").split("\0")
    rows, has_json = base_rows(root, base)
    problems = merge_problems(rows, head, [pr_body(body_file), *commits], has_json)
    for p in problems:
        print(f"status merge-check: {p}", file=sys.stderr)
    if not problems:
        print("status merge-check: every listed ID's row changed and no done row regressed")
    return 1 if problems else 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("generate", help=f"rewrite the tables of {DOC_PATH}")
    sub.add_parser("check", help="verify the rows and the document")
    merge = sub.add_parser("merge-check", help="verify a pull request against its base")
    merge.add_argument("--base", required=True, help="the base commit of the pull request")
    merge.add_argument("--body-file", help="the pull-request body (default: $GITHUB_EVENT_PATH)")
    args = parser.parse_args(argv)
    try:
        if args.command == "generate":
            return cmd_generate(args.root)
        if args.command == "check":
            return cmd_check(args.root)
        return cmd_merge_check(args.root, args.base, args.body_file)
    except StatusError as e:
        print(f"status: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
