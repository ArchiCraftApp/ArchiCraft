#!/usr/bin/env python3
"""Writes THIRD-PARTY.md, the notices of the components the ArchiCraft binaries contain (SRS
NFR-LEG-001), from cargo-about's JSON output and the notices of third-party/supplements.toml.

scripts/third-party.sh runs it. It fails while a shipped crate has only a bare licence template
("Copyright (c) <year> <copyright holders>"), which cargo-about falls back to when a crate ships
no licence file, and when a notice of supplements.toml names a crate that no longer ships.
Needs Python 3.11 or later (tomllib).

Usage: python3 scripts/third_party.py <cargo-about.json> <THIRD-PARTY.md>
"""

import json
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# The copyright line of a bare licence template. The appendices of the Apache and LGPL texts
# carry placeholders of their own ("[yyyy]", "<name of author>"); they belong to those licences.
PLACEHOLDER = re.compile(r"<copyright holders>|<owner>|<copyright notice>")

INTRO = """\
# Third-party licences

ArchiCraft is licensed under the Creative Commons Attribution 4.0 International licence
(CC BY 4.0, see LICENSE). The ArchiCraft program contains the components listed here, which
keep their own licences. The distribution model of ArchiCraft is still open (SRS O-5); until it
is decided, components are chosen under permissive licences. The one exception, accepted on
2026-10-27, is wayland-protocols-plasma in the Linux build, which contains KDE protocol files
under the GNU Lesser General Public License v2.1 or later; its notice lists them.
wayland-protocols-misc, also in the Linux build, contains a copy of one of these files
(server-decoration.xml); whether the exception covers it is not decided yet. The overview below
lists the licences these components use.

This file is generated by `scripts/third-party.sh` with cargo-about from `Cargo.lock`, for the
Linux (x86_64), macOS (Apple silicon) and Windows (x86_64) packages. Do not edit it by hand.
"""

STANDARD_LIBRARY = """\
## Rust standard library

The program contains the Rust standard library (std, core and alloc, with the crates they are
built from) of the Rust toolchain named in `rust-toolchain.toml`, copyright the Rust Project
Developers, licensed under the MIT licence or the Apache License, Version 2.0, at your option
(https://github.com/rust-lang/rust/blob/master/COPYRIGHT). ArchiCraft uses it under the Apache
License, Version 2.0, whose text is under "Licence texts".
"""

SCHEMA_FILES = """\
## IFCX schema files

The program contains unmodified copies of four IFCX schema files that buildingSMART
International publishes at https://ifcx.dev: `ifc@v5a.ifcx`, `prop@v5a.ifcx`,
`ifc-mat@v1.0.0.ifcx` and `usd@v1.ifcx`, taken from https://github.com/buildingSMART/IFCx.dev
at commit 36010c0e1069043f964a7dff8367e3e910255ebb. The source states no licence for them
(checked on 2026-10-23).
"""


def crate_key(krate):
    return f"{krate['name']} {krate['version']}"


def licence_ids(expression):
    return sorted(set(re.findall(r"[A-Za-z0-9.+-]+", expression)) - {"AND", "OR", "WITH"})


def main(json_path, output_path):
    data = json.loads(Path(json_path).read_text(encoding="utf-8"))
    notices = tomllib.loads((ROOT / "third-party/supplements.toml").read_text(encoding="utf-8"))["notice"]
    shipped = {crate_key(c["package"]): c for c in data["crates"]}
    names = {lic["id"]: lic["name"] for lic in data["licenses"]}
    errors = []

    supplied = {}
    for notice in notices:
        for key in notice["crates"]:
            if key not in shipped:
                errors.append(f"third-party/supplements.toml names {key}, which no longer ships")
            supplied[key] = notice

    # (heading parts, text, crates, source) per licence text; cargo-about's entries first, minus
    # the crates a supplement covers, then the supplements.
    entries = []
    for lic in data["licenses"]:
        crates = [crate_key(u["crate"]) for u in lic["used_by"] if crate_key(u["crate"]) not in supplied]
        if crates:
            entries.append(([f"{lic['name']} ({lic['id']})"], [lic["id"]], lic["text"], crates, None))
    for notice in notices:
        crates = [key for key in notice["crates"] if key in shipped]
        text = (ROOT / notice["file"]).read_text(encoding="utf-8")
        licence = notice["licence"]
        heading = f"{names[licence]} ({licence})" if licence in names else licence
        entries.append(([heading], licence_ids(licence), text, crates, notice["source"]))

    # One entry per text and source: a file that covers two licences (sha1_smol) is shown once,
    # and a supplement keeps its own source line even where its text equals another notice.
    merged = {}
    # The licences in use: each crate counts once per licence whose text it is shown under.
    users = {}
    for heading, ids, text, crates, source in entries:
        text = text.replace("\r\n", "\n").strip("\n")
        entry = merged.setdefault((text, source), {"heading": [], "crates": set()})
        entry["heading"] += [h for h in heading if h not in entry["heading"]]
        entry["crates"].update(crates)
        for licence in ids:
            users.setdefault(licence, set()).update(crates)
    for (text, _), entry in merged.items():
        if PLACEHOLDER.search(text):
            errors.append(
                "bare licence template for " + ", ".join(sorted(entry["crates"]))
                + ": add a clarification to about.toml or a notice to third-party/supplements.toml"
            )
    if errors:
        sys.exit("\n".join(errors))

    licence_of = {key: c["license"] for key, c in shipped.items()}
    for key, notice in supplied.items():
        if key in licence_of:
            licence_of[key] = notice["licence"]
    counts = {licence: len(crates) for licence, crates in users.items()}

    out = [INTRO, "\n## Overview\n\n| Licence | Crates |\n|---|---:|\n"]
    for licence, count in sorted(counts.items(), key=lambda item: (-item[1], item[0])):
        label = f"{names[licence]} ({licence})" if licence in names else licence
        out.append(f"| {label} | {count} |\n")
    out += ["\n", STANDARD_LIBRARY, "\n", SCHEMA_FILES, "\n## Crates\n\n"]
    for c in data["crates"]:
        out.append(f"- {crate_key(c['package'])}: {licence_of[crate_key(c['package'])]}\n")
    out.append("\n## Licence texts\n")
    for (text, source), entry in sorted(merged.items(), key=lambda item: (item[1]["heading"], sorted(item[1]["crates"]))):
        out.append(f"\n### {', '.join(entry['heading'])}\n\n")
        out.append(f"Used by: {', '.join(sorted(entry['crates']))}\n")
        if source:
            out.append(f"\n{source}\n")
        out.append(f"\n```text\n{text}\n```\n")
    Path(output_path).write_text("".join(out), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
