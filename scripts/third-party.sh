#!/usr/bin/env bash
# Regenerates THIRD-PARTY.md, the notices of the components the ArchiCraft binaries contain
# (SRS NFR-LEG-001), with cargo-about from Cargo.lock (configuration about.toml, notices for
# crates without a licence file in third-party/supplements.toml, rendered by
# scripts/third_party.py), and third-party/not-shipped.txt, the Cargo.lock packages the
# binaries do not contain (dev and build dependencies, crates of other platforms). Run it after
# every change to Cargo.lock: crates/archicraft-app/tests/third_party.rs fails until both files
# match it again. The package scripts ship THIRD-PARTY.md next to LICENSE. Needs Python 3.11 or
# later; the pinned cargo-about is installed when missing.
# Usage: scripts/third-party.sh
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

# Pinned, like the other tools of docs/technology-choices.md; installed when missing.
version=0.9.2
if [ "$(cargo about --version 2>/dev/null)" != "cargo-about $version" ]; then
    echo "Installing cargo-about $version" >&2
    cargo install cargo-about --version "$version" --locked --features cli
fi

# --offline takes every licence text from the crate sources, so the output depends on
# Cargo.lock alone and not on the network; cargo fetch first downloads the crates of all
# platforms. scripts/third_party.py adds the notices of third-party/supplements.toml and writes
# the Markdown.
cargo fetch --locked
json="$(mktemp "${TMPDIR:-/tmp}/third-party.XXXXXX")"
trap 'rm -f "$json"' EXIT
cargo about generate --offline --locked --fail --format json \
    --manifest-path crates/archicraft-app/Cargo.toml --config about.toml --output-file "$json"
python3 scripts/third_party.py "$json" THIRD-PARTY.md

# "name version" of every registry package in Cargo.lock.
lock_packages() {
    awk '
        function flush() { if (name != "" && registry) print name " " version }
        /^\[\[package\]\]/ { flush(); name = ""; version = ""; registry = 0 }
        /^name = /         { gsub(/"/, "", $3); name = $3 }
        /^version = /      { gsub(/"/, "", $3); version = $3 }
        /^source = "registry\+/ { registry = 1 }
        END { flush() }
    ' Cargo.lock | LC_ALL=C sort
}

# "name version" of every crate THIRD-PARTY.md lists ("- name version: licence").
listed() {
    sed -n 's/^- \([^ ]*\) \([^:]*\): .*/\1 \2/p' THIRD-PARTY.md | LC_ALL=C sort
}

{
    echo "# The Cargo.lock packages the ArchiCraft binaries do not contain (dev and build"
    echo "# dependencies, crates of other platforms), so THIRD-PARTY.md does not list them."
    echo "# Generated by scripts/third-party.sh; do not edit."
    LC_ALL=C comm -23 <(lock_packages) <(listed)
} >third-party/not-shipped.txt

shipped=$(listed | wc -l | tr -d ' ')
other=$(grep -vc '^#' third-party/not-shipped.txt)
echo "THIRD-PARTY.md: $shipped crates; third-party/not-shipped.txt: $other packages"
